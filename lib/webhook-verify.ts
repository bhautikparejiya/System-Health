/** Verifies a HighLevel webhook against the raw request body. */
export function verifyGhlWebhook(rawBody: string, headers: Headers): boolean {
  try {
    const ghlSig = headers.get("x-ghl-signature");
    if (ghlSig) {
      return verify(null, Buffer.from(rawBody, "utf8"), ED25519_KEY, Buffer.from(ghlSig, "base64"));
    }
    const whSig = headers.get("x-wh-signature");
    if (whSig) {
      const v = createVerify("SHA256");
      v.update(rawBody);
      v.end();
      return v.verify(RSA_KEY, whSig, "base64");
    }
  } catch {
    return false;
  }
  return false;
}
